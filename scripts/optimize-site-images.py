"""Build responsive, lossy web derivatives from assets/images without modifying originals."""
from __future__ import annotations
import json, re, unicodedata
from pathlib import Path
from PIL import Image, ImageOps, features

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets'/'images'
OUTPUT=ROOT/'assets'/'optimized'/'site'
SIZES=(800,1600)
MIN_BYTES=50*1024

def slugify(value: str) -> str:
    value=value.replace('ı','i').replace('İ','i')
    value=unicodedata.normalize('NFKD',value).encode('ascii','ignore').decode('ascii').lower()
    return re.sub(r'[^a-z0-9]+','-',value).strip('-')

def save_variant(image: Image.Image, target: Path, fmt: str) -> None:
    target.parent.mkdir(parents=True,exist_ok=True)
    if fmt=='WEBP': image.save(target,'WEBP',quality=84,method=6)
    else: image.save(target,'AVIF',quality=48,speed=6)

def main() -> None:
    if not features.check('webp'): raise SystemExit('Pillow WebP encoder required')
    avif=features.check('avif')
    sources=sorted(p for p in SOURCE.iterdir() if p.is_file() and p.suffix.lower() in {'.png','.jpg','.jpeg'} and p.stat().st_size>=MIN_BYTES)
    stems={}
    for p in sources: stems.setdefault(slugify(p.stem),[]).append(p)
    manifest={}
    for source in sources:
        key=slugify(source.stem)
        if len(stems[key])>1: key+=f'-{abs(hash(source.name))%1000000:06d}'
        with Image.open(source) as original:
            image=ImageOps.exif_transpose(original)
            image=image.convert('RGBA' if 'A' in image.getbands() else 'RGB')
            width,height=image.size
            rec={'source':source.relative_to(ROOT).as_posix(),'width':width,'height':height,'sourceBytes':source.stat().st_size,'webp':[],'avif':[]}
            previous_size=None
            for max_edge in SIZES:
                edge=min(max_edge,max(width,height))
                if edge==previous_size: continue
                previous_size=edge
                variant=image.copy()
                variant.thumbnail((edge,edge),Image.Resampling.LANCZOS)
                for fmt,ext in [('WEBP','webp')]:
                    target=OUTPUT/f'{key}-{edge}.{ext}';save_variant(variant,target,fmt)
                    rec['webp'].append({'path':target.relative_to(ROOT).as_posix(),'width':variant.width,'height':variant.height,'bytes':target.stat().st_size})
                if avif:
                    target=OUTPUT/f'{key}-{edge}.avif';save_variant(variant,target,'AVIF')
                    webp_bytes=rec['webp'][-1]['bytes']
                    if target.stat().st_size<webp_bytes:
                        rec['avif'].append({'path':target.relative_to(ROOT).as_posix(),'width':variant.width,'height':variant.height,'bytes':target.stat().st_size})
                    else: target.unlink()
        manifest[rec['source']]=rec
    OUTPUT.mkdir(parents=True,exist_ok=True)
    (OUTPUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    client={key:{'width':value['width'],'height':value['height'],
        'webp':[[item['path'],item['width'],item['height']] for item in value['webp']],
        'avif':[[item['path'],item['width'],item['height']] for item in value['avif']]}
        for key,value in manifest.items()}
    helper='''/* Generated by scripts/optimize-site-images.py. Original assets remain untouched. */
window.BekamarSiteImages = (() => {
  const images = __IMAGE_DATA__;
  const escape = value => String(value).replace(/[&<>"']/g, character => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[character]));
  const keyFor = source => String(source || '').replace(/^(?:\\.\\.\\/)+/, '').replace(/^\\//, '');
  const prefixed = (path, prefix) => `${prefix || ''}${path}`;
  const sourceSet = (variants, prefix) => variants.map(([path, width]) => `${prefixed(path, prefix)} ${width}w`).join(', ');
  function attach(image, source, prefix = '', sizes = '100vw') {
    const key = keyFor(source), entry = images[key];
    if (!entry) return image;
    let picture = image.parentElement?.matches('picture.site-image-picture') ? image.parentElement : null;
    if (!picture) {
      picture = document.createElement('picture');
      picture.className = 'site-image-picture';
      if (image.parentNode) image.replaceWith(picture);
      picture.append(image);
    }
    picture.replaceChildren();
    if (entry.avif.length) {
      const avif = document.createElement('source');
      avif.type = 'image/avif'; avif.srcset = sourceSet(entry.avif, prefix); avif.sizes = sizes;
      picture.append(avif);
    }
    const webp = document.createElement('source');
    webp.type = 'image/webp'; webp.srcset = sourceSet(entry.webp, prefix); webp.sizes = sizes;
    picture.append(webp);
    image.src = prefixed(key, prefix);
    image.width = entry.width; image.height = entry.height; image.decoding = 'async';
    picture.append(image);
    return picture;
  }
  function original(image, source, prefix = '') {
    const key = keyFor(source), entry = images[key];
    const picture = image.parentElement?.matches('picture.site-image-picture') ? image.parentElement : null;
    if (picture) picture.replaceChildren(image);
    image.src = prefixed(key, prefix);
    if (entry) { image.width = entry.width; image.height = entry.height; }
    image.decoding = 'async';
    image.loading = 'eager';
    return image;
  }
  function markup(source, {prefix = '', className = '', alt = '', sizes = '100vw', loading = 'lazy'} = {}) {
    const image = document.createElement('img');
    image.className = className; image.alt = alt; image.loading = loading;
    const picture = attach(image, source, prefix, sizes);
    return picture.outerHTML;
  }
  function path(source, prefix = '') {
    const key = keyFor(source), entry = images[key];
    return prefixed(entry ? entry.webp[entry.webp.length - 1][0] : key, prefix);
  }
  function background(source, prefix = '', small = false) {
    const key = keyFor(source), entry = images[key];
    if (!entry) return `url("${prefixed(key, prefix)}")`;
    const webp = small ? entry.webp[0] : entry.webp[entry.webp.length - 1];
    const avif = small ? entry.avif[0] : entry.avif[entry.avif.length - 1];
    const fallback = prefixed(webp[0], prefix);
    const preferred = avif ? `url("${prefixed(avif[0], prefix)}") type("image/avif"), ` : '';
    return `image-set(${preferred}url("${fallback}") type("image/webp"))`;
  }
  return {attach, original, markup, path, background};
})();
'''.replace('__IMAGE_DATA__',json.dumps(client,ensure_ascii=False,separators=(',',':')))
    (ROOT/'js'/'site-images.js').write_text(helper,encoding='utf-8')
    before=sum(r['sourceBytes'] for r in manifest.values())
    after=sum(v['bytes'] for r in manifest.values() for v in r['webp'])
    print(f'Optimized {len(manifest)} source images; {before/1024/1024:.2f} MB source -> {after/1024/1024:.2f} MB WebP variants ({(1-after/before)*100:.1f}% smaller).')
    print(f'AVIF variants retained: {sum(len(r["avif"]) for r in manifest.values())}; originals left unchanged.')
if __name__=='__main__': main()
